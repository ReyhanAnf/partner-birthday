/**
 * Resolves an asset path to ensure it functions under any base path
 * (e.g., GitHub Pages subpaths like /repo-name/ or relative deployments).
 */
export const resolveAssetUrl = (assetPath: string): string => {
  if (!assetPath) return '';
  if (
    assetPath.startsWith('http://') ||
    assetPath.startsWith('https://') ||
    assetPath.startsWith('data:') ||
    assetPath.startsWith('blob:')
  ) {
    return assetPath;
  }
  const base = import.meta.env.BASE_URL || './';
  const cleanBase = base.endsWith('/') ? base : `${base}/`;
  const cleanPath = assetPath.startsWith('/') ? assetPath.slice(1) : assetPath;
  return `${cleanBase}${cleanPath}`;
};

const normalizeAsset = (asset: MediaAsset): MediaAsset => ({
  ...asset,
  url: resolveAssetUrl(asset.url),
  posterUrl: asset.posterUrl ? resolveAssetUrl(asset.posterUrl) : undefined,
});

